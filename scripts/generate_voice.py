#!/usr/bin/env python3
"""Generate Indonesian narration MP3s and word-timed subtitle chunks using Edge TTS."""
import argparse
import asyncio
import json
from pathlib import Path

import edge_tts
from mutagen.mp3 import MP3

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "episode-01.json"
OUT = ROOT / "public" / "audio" / "episode-01"
CAPTION_OUT = ROOT / "src" / "generated-captions.ts"
DEFAULT_VOICE = "id-ID-GadisNeural"
FPS = 30
TICKS_PER_SECOND = 10_000_000


def make_chunks(words, scene_start):
    chunks = []
    for offset in range(0, len(words), 4):
        group = words[offset:offset + 4]
        if not group:
            continue
        start = scene_start + round(group[0]["offset"] / TICKS_PER_SECOND * FPS)
        last = group[-1]
        end = scene_start + round((last["offset"] + last["duration"]) / TICKS_PER_SECOND * FPS)
        chunks.append({"startFrame": start, "endFrame": max(start + 1, end), "text": " ".join(w["text"] for w in group)})
    return chunks


async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--voice", default=DEFAULT_VOICE)
    parser.add_argument("--rate", default="+0%")
    parser.add_argument("--pitch", default="+0Hz")
    args = parser.parse_args()

    episode = json.loads(DATA.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = []
    all_captions = []

    for index, scene in enumerate(episode["scenes"], start=1):
        target = OUT / f"scene-{index:02d}.mp3"
        communicate = edge_tts.Communicate(scene["narration"].strip(), args.voice, rate=args.rate, pitch=args.pitch)
        word_events = []
        with target.open("wb") as audio_file:
            async for event in communicate.stream():
                if event["type"] == "audio":
                    audio_file.write(event["data"])
                elif event["type"] == "WordBoundary":
                    data = event["data"]
                    word_events.append({
                        "text": data["text"],
                        "offset": int(data["offset"]),
                        "duration": int(data["duration"])
                    })

        duration = MP3(str(target)).info.length
        scene_start_frame = round(scene["start"] * FPS)
        captions = make_chunks(word_events, scene_start_frame)
        all_captions.append({"scene": index, "captions": captions})
        scene_seconds = scene["end"] - scene["start"]
        manifest.append({
            "scene": index,
            "file": f"audio/episode-01/scene-{index:02d}.mp3",
            "duration_seconds": round(duration, 2),
            "scene_seconds": round(scene_seconds, 2),
            "fits_scene": duration <= scene_seconds,
            "word_boundaries": len(word_events),
            "narration": scene["narration"]
        })
        status = "OK" if duration <= scene_seconds else "WARNING: narration exceeds scene"
        print(f"{status} scene {index}: audio {duration:.2f}s / scene {scene_seconds:.2f}s")

    manifest_path = ROOT / "data" / "episode-01-audio.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    CAPTION_OUT.write_text(
        "// Generated by scripts/generate_voice.py. Do not edit by hand.\n"
        "export type TimedCaption = {startFrame: number; endFrame: number; text: string};\n"
        "export const generatedCaptions: TimedCaption[][] = "
        + json.dumps([item["captions"] for item in all_captions], ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8"
    )
    print(f"Audio manifest: {manifest_path}")
    print(f"Timed captions: {CAPTION_OUT}")


if __name__ == "__main__":
    asyncio.run(main())
